reg, tri = load()
page = render(reg, tri)
html_page = render_html(reg, tri)

if '--check' in sys.argv:
    stale = [str(f.relative_to(REPO)) for f, want in ((OUT, page), (OUT_HTML, html_page))
             if not f.exists() or f.read_text() != want]
    if stale:
        print('stale against the register or the triage: ' + ', '.join(stale))
        print('  rebuild: python3 tools/build-open-items-agenda.py')
        sys.exit(1)
    print(f'open-items agenda current ({len(reg)} items)')
    sys.exit(0)

OUT.write_text(page)
OUT_HTML.write_text(html_page)
from collections import Counter
c = Counter(t['session'] for t in tri.values())
print(f'{OUT.relative_to(REPO)}  {len(page) / 1024:.0f} KB')
print(f'{OUT_HTML.relative_to(REPO)}  {len(html_page) / 1024:.0f} KB')
print('  ' + ' · '.join(f'{k} {c[k]}' for k, _, _ in SESSIONS))
