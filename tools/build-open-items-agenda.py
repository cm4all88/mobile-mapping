        h += [f'<h2>{esc(title)} <span class="n">&mdash; {len(items)}</span></h2>',
              f'<p class="blurb">{esc(blurb)}</p>']
        for i in items:
            r, t = reg[i], tri[i]
            tags = [r['priority'], TYPE_WORD[r['type']], r['affected_stage']]
            if t['effort']:
                tags.append(t['effort'])
            h += [f'<div class="item {"p1" if r["priority"] == "P1" else ""}">',
                  f'<h3><span class="id">{esc(i)}</span>{esc(r["question"])}</h3>',
                  '<p class="tags">' + ' &middot; '.join(esc(x) for x in tags) + '</p>']
            if r['why_it_matters']:
                h.append('<p class="why"><span class="lbl">Why it matters</span>'
                         + esc(r['why_it_matters']) + '</p>')
            h.append('<p class="how"><span class="lbl">How to settle it</span>'
                     + esc(t['note']) + '</p>')
            links = []
            if t['waits_on']:
                links.append('Waits on ' + esc(t['waits_on']))
            if holds.get(i):
                links.append('Holds up ' + esc(', '.join(holds[i])))
            if r['resolution']:
                links.append('Part answered: ' + esc(r['resolution']))
            if links:
                h.append('<p class="link">' + ' &nbsp;·&nbsp; '.join(links) + '</p>')
