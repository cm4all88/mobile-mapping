#!/usr/bin/env python3
"""Turn the open-item register into an agenda somebody can work from.

    python3 tools/build-open-items-agenda.py          # write the agenda
    python3 tools/build-open-items-agenda.py --check  # fail if it is stale

WHY THIS EXISTS

`master-register.csv` holds eighty open items and says, for each, what the
question is and why it matters. What it does not say is *how you would settle
it* -- and eighty undifferentiated questions is not a plan, it is a reason not
to start. Three of them are answered by walking out to the vehicle. Fourteen are
a single email to Trimble. Thirty-four need nobody but Parametrix and no
equipment at all.

WHAT IS DERIVED AND WHAT IS DECLARED

  derived   the question, why it matters, the priority, the type and the stage,
            all out of the register. Nothing is restated here.

  declared  `open-items-triage.csv` -- how each item would be settled, how long
            it would take, and what it waits on. That is judgement, so it is
            written down where it can be argued with rather than buried in this
            script.

Both files must cover exactly the same ids, and a `waits_on` must name a real
item. `--check` is a gate in `tools/check-all.py`, so an item added to the
register cannot sit untriaged and invisible.
"""
import csv, pathlib, sys

REPO = pathlib.Path(__file__).resolve().parent.parent
REG = REPO / 'deliverables/_control/master-register.csv'
TRI = REPO / 'deliverables/_control/open-items-triage.csv'
OUT = REPO / 'deliverables/_control/open-items-agenda.md'
OUT_HTML = REPO / 'deliverables/_control/open-items-agenda.html'

SESSIONS = [
    ('look', 'Go and look',
     'Answered by looking at the system, the vehicle or a dialog. No decision, no '
     'test, nobody else involved. These are the ones to clear first, because '
     'several of the others are conditional on them.'),
    ('decide', 'Parametrix decides',
     'No equipment, no vendor, no test. Somebody with the authority writes the '
     'answer down. This is the largest group and the cheapest, and it is what '
     'keeps every document in the set a living draft.'),
    ('ask', 'Ask Trimble',
     'One message to the dealer or to support. Group them and send them together; '
     'the answers are not urgent individually but several decisions wait on them.'),
    ('desk', 'At the workstation',
     'TBC and a dataset we already have. No collection needed. Most are an hour; '
     'the three marked a day are the ones that produce numbers other decisions '
     'need.'),
    ('drive', 'Needs a collection',
     'A real mission, or a control survey beside one. The expensive group, and '
     'the one to fold into work that is happening anyway rather than schedule on '
     'its own.'),
]
PRI = {'P1': 0, 'P2': 1, 'P3': 2}
EFFORT_ORDER = {'minutes': 0, 'hour': 1, 'half-day': 2, 'day': 3, 'mission': 4, '': 5}
TYPE_WORD = {'decision': 'Parametrix decision', 'test': 'test', 'vendor': 'vendor question'}


def load():
    reg = {r['id']: r for r in csv.DictReader(REG.open(encoding='utf-8'))}
    tri = {r['id']: r for r in csv.DictReader(TRI.open(encoding='utf-8'))}
    missing = sorted(set(reg) - set(tri))
    extra = sorted(set(tri) - set(reg))
    if missing:
        sys.exit(f'{TRI.name}: no triage for {missing} — every register item needs one')
    if extra:
        sys.exit(f'{TRI.name}: {extra} are not in {REG.name}')
    known = {s for s, _, _ in SESSIONS}
    for i, t in tri.items():
        if t['session'] not in known:
            sys.exit(f'{TRI.name}: {i} has session "{t["session"]}", not one of {sorted(known)}')
        if t['waits_on'] and t['waits_on'] not in reg:
            sys.exit(f'{TRI.name}: {i} waits on {t["waits_on"]}, which is not in the register')
    return reg, tri


def render(reg, tri):
    # what each item is holding up, read off the waits_on column
    holds = {}
    for i, t in tri.items():
        if t['waits_on']:
            holds.setdefault(t['waits_on'], []).append(i)

    # Everything that can be settled this week without leaving the building:
    # every look, whatever its priority, because each is minutes and several
    # others are conditional on it; then the P1 decisions nothing is holding up.
    first = [i for i, t in tri.items()
             if not t['waits_on']
             and (t['session'] == 'look'
                  or (t['session'] == 'decide' and reg[i]['priority'] == 'P1'))]
    first.sort(key=lambda i: (0 if tri[i]['session'] == 'look' else 1,
                              EFFORT_ORDER[tri[i]['effort']], i))

    out = [
        '# Open items — an agenda',
        '',
        '*Built by `tools/build-open-items-agenda.py`. Do not edit this file; edit*',
        '*`open-items-triage.csv`, which is the judgement, or `master-register.csv`,*',
        '*which is the question.*',
        '',
        f'**{len(reg)} open items.** The register says what each question is and why it '
        'matters. This says how you would settle it, grouped so a session of work is a '
        'group rather than a scatter.',
        '',
        '| | |',
        '|---|---|',
    ]
    for key, title, _ in SESSIONS:
        n = sum(1 for t in tri.values() if t['session'] == key)  # noqa: F402
        p1 = sum(1 for i, t in tri.items()
                 if t['session'] == key and reg[i]['priority'] == 'P1')
        out.append(f'| **{title}** | {n} items, {p1} of them P1 |')
    looks = sum(1 for i in first if tri[i]['session'] == 'look')
    out += ['',
            '## Start here',
            '',
            f'Everything that can be settled without leaving the building and without '
            f'waiting on anything else: the {looks} things you can simply go and look '
            f'at, then the P1 decisions nothing is holding up. Shortest first.',
            '',
            '| Item | Takes | What it is | Unblocks |',
            '|---|---|---|---|']
    for i in first:
        t, r = tri[i], reg[i]
        q = r['question'] if len(r['question']) <= 92 else r['question'][:90].rstrip() + '…'
        out.append(f'| **{i}** | {t["effort"] or "—"} | {q} | '
                   f'{", ".join(holds.get(i, [])) or "—"} |')
    out.append('')

    for key, title, blurb in SESSIONS:
        items = [i for i, t in tri.items() if t['session'] == key]
        items.sort(key=lambda i: (PRI[reg[i]['priority']], EFFORT_ORDER[tri[i]['effort']], i))
        out += ['', f'## {title} — {len(items)}', '', blurb, '']
        for i in items:
            t, r = tri[i], reg[i]
            bits = [r['priority'], TYPE_WORD[r['type']], r['affected_stage']]
            if t['effort']:
                bits.append(t['effort'])
            out += [f'### {i} · {r["question"]}',
                    '',
                    '· '.join(f'**{b}** ' for b in bits).strip(),
                    '']
            if r['why_it_matters']:
                out += [f'*Why it matters.* {r["why_it_matters"]}', '']
            out += [f'*How to settle it.* {t["note"]}', '']
            links = []
            if t['waits_on']:
                links.append(f'Waits on **{t["waits_on"]}**')
            if holds.get(i):
                links.append('Holds up **' + '**, **'.join(holds[i]) + '**')
            if r['resolution']:
                links.append(f'Part answered: {r["resolution"][:140]}')
            if links:
                out += ['> ' + ' · '.join(links), '']
    out += ['',
            '---',
            '',
            'Every item here is open. Until an item is resolved and the register says '
            'so, the document it affects stays a living draft and nothing in it may be '
            'quoted to a client as an existing Parametrix standard.',
            '']
    return '\n'.join(out)


def esc(t):
    return (str(t).replace('&', '&amp;').replace('<', '&lt;').replace('>', '&gt;'))


